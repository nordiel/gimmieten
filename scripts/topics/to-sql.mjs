// Writes the topic ids and categories from src/data/topics.ts as a SQL
// migration, so the server can validate dealt topics. Re-run after adding topics:
//   node scripts/topics/to-sql.mjs
import { build } from 'esbuild';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const dir = mkdtempSync(join(tmpdir(), 'topics-'));
const out = join(dir, 'topics.mjs');
await build({ entryPoints: ['src/data/topics.ts'], outfile: out, bundle: true, format: 'esm', platform: 'node', logLevel: 'warning' });
const { TOPICS } = await import(pathToFileURL(out).href);
rmSync(dir, { recursive: true, force: true });

const quote = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = TOPICS.map((t) => `  (${quote(t.id)}, ${quote(t.category)})`).join(',\n');
const sql = `-- Generated by scripts/topics/to-sql.mjs from src/data/topics.ts. Do not edit by hand.
insert into public.topics (id, category) values
${rows}
on conflict (id) do update set category = excluded.category;
`;
const file = 'supabase/migrations/20261027000100_seed_topics.sql';
writeFileSync(file, sql);
console.log(`Wrote ${TOPICS.length} topics to ${file}`);
